"""Stage 5: embedding-based near-duplicate check across the train/val/test split.

    python -m src.leakage_embeddings

Uses cosine similarity of the frozen ResNet50 features, which is less sensitive to crops, zoom and
brightness than the pixel-based check of Stage 3 and 4. It only REPORTS: it never changes the split.
Reference values (pairs known to be the same photograph, and pairs of different classes) are printed
so that a threshold can be judged instead of guessed. Inspect the saved picture before deciding.
"""
import numpy as np
import pandas as pd

from src import config

THRESHOLDS = (0.95, 0.90, 0.85, 0.80, 0.75)


def cosine_matrix(features):
    z = features / (np.linalg.norm(features, axis=1, keepdims=True) + 1e-12)
    sim = z @ z.T
    np.fill_diagonal(sim, -1.0)
    return sim


def cross_split_pairs(sim, labels, splits, threshold):
    """Index pairs (i, j), i < j, of the same class in different splits with similarity >= threshold."""
    ii, jj = np.where(np.triu(sim >= threshold, k=1))
    return [(int(i), int(j)) for i, j in zip(ii, jj) if labels[i] == labels[j] and splits[i] != splits[j]]


def reference_values(sim, labels, groups):
    """Cosine values of pairs in the same photograph group and of pairs from different classes."""
    iu = np.triu_indices(sim.shape[0], k=1)
    s = sim[iu]
    same_group = groups[iu[0]] == groups[iu[1]]
    same_label = labels[iu[0]] == labels[iu[1]]
    within = s[same_group & same_label]
    diff_class = s[~same_label]
    return within, diff_class


def main():
    from PIL import Image, ImageDraw

    from src.features import load_features

    if not config.FEATURES_FILE.exists():
        raise SystemExit("Run python -m src.features first.")
    d = load_features()
    feats, files, labels, groups, splits = (d[k] for k in ("features", "files", "labels", "groups", "splits"))
    sim = cosine_matrix(feats)
    within, diff = reference_values(sim, labels, groups)

    L = ["# Embedding-Based Duplicate Check (Stage 5)\n",
         "Generated by `src/leakage_embeddings.py`. The split was not changed by this check.\n",
         "## Reference values (cosine similarity of ResNet50 features)\n",
         f"- Pairs in the same photograph group (n={len(within)}): 5th percentile {np.percentile(within, 5):.3f}, "
         f"25th {np.percentile(within, 25):.3f}, median {np.median(within):.3f}",
         f"- Pairs from different classes (n={len(diff)}): median {np.median(diff):.3f}, "
         f"95th percentile {np.percentile(diff, 95):.3f}, 99th {np.percentile(diff, 99):.3f}, "
         f"maximum {diff.max():.3f}\n",
         "A threshold is only meaningful if it lies above what different-class pairs reach and below what "
         "same-photograph pairs reach.\n",
         "## Same-class pairs in different splits\n",
         "| Threshold | Pairs | Test images involved | Validation images involved |", "|---|---|---|---|"]
    show_floor = float(np.percentile(diff, 99))
    for thr in THRESHOLDS:
        pr = cross_split_pairs(sim, labels, splits, thr)
        inv = {i for p in pr for i in p}
        t = sum(splits[i] == "test" for i in inv)
        v = sum(splits[i] == "val" for i in inv)
        L.append(f"| {thr} | {len(pr)} | {t} | {v} |")
    L.append("\nPer class at the threshold equal to the 99th percentile of different-class pairs "
             f"({show_floor:.3f}):\n")
    pr = cross_split_pairs(sim, labels, splits, show_floor)
    L.append("| Class | Cross-split pairs | Test images involved |\n|---|---|---|")
    for lab in sorted(set(labels)):
        sub = [p for p in pr if labels[p[0]] == lab]
        inv = {i for p in sub for i in p}
        L.append(f"| {lab} | {len(sub)} | {sum(splits[i] == 'test' for i in inv)} |")

    # picture and csv of the highest-ranked pairs
    pr_sorted = sorted(pr, key=lambda p: -sim[p[0], p[1]])
    rows = [{"cosine": round(float(sim[i, j]), 4), "label": labels[i], "file_a": files[i], "split_a": splits[i],
             "group_a": int(groups[i]), "file_b": files[j], "split_b": splits[j], "group_b": int(groups[j])}
            for i, j in pr_sorted]
    pd.DataFrame(rows).to_csv(config.REPORTS_DIR / "embedding_cross_split_pairs.csv", index=False)
    if pr_sorted:
        pick = pr_sorted[:12]
        if len(pr_sorted) > 12:
            step = max(1, (len(pr_sorted) - 12) // 12)
            pick += pr_sorted[12::step][:12]
        s, cols = 150, 4
        W = Image.new("RGB", (cols * 2 * s, ((len(pick) + cols - 1) // cols) * (s + 14)), "white")
        d = ImageDraw.Draw(W)
        for q, (i, j) in enumerate(pick):
            x, y = (q % cols) * 2 * s, (q // cols) * (s + 14)
            for m, idx in enumerate((i, j)):
                p = config.DATA_PROCESSED / splits[idx] / labels[idx] / files[idx]
                with Image.open(p) as im:
                    W.paste(im.convert("RGB").resize((s, s)), (x + m * s, y + 14))
            d.text((x + 2, y + 1), f"{sim[i, j]:.2f} {labels[i][:7]} {splits[i]}|{splits[j]}", fill="black")
        config.EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
        W.save(config.EVIDENCE_DIR / "07_embedding_cross_split_pairs.png")
        L.append("\nPicture of the highest and evenly sampled lower-ranked pairs: "
                 "`reports/evidence/07_embedding_cross_split_pairs.png`. List: `reports/embedding_cross_split_pairs.csv`.")
    L.append("\n## How to read this\n- Look at the picture. Pairs that show the same scene are copies that the "
             "split should keep together. Pairs of different photographs are look-alikes.\n"
             "- If copies exist across splits, the fix is to regroup and re-split, which needs approval.")
    config.EMBEDDING_LEAK_REPORT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"Wrote {config.EMBEDDING_LEAK_REPORT}")
    print("\n".join(L[2:12]))


if __name__ == "__main__":
    main()
